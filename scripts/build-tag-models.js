/**
 * Regenerates lib/tagModels.js from the per-model drivers, and marks those
 * drivers deprecated.
 *
 * The 97 model drivers carry no behaviour - identical device.js, identical
 * driver.js apart from the hwType they filter on, and driver manifests that
 * differ only in the display name, the images and the battery count. This
 * lifts the two bits that are worth keeping (name and batteries, keyed by
 * hwType) into a lookup the generic `tag` driver uses, and flags each model
 * driver `"deprecated": true` so it disappears from Add Device while already
 * paired devices keep working.
 *
 * Run: node scripts/build-tag-models.js
 */

const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const DRIVERS = path.join(ROOT, 'drivers');
const OUT = path.join(ROOT, 'lib', 'tagModels.js');
const GENERIC = 'tag';

const dirs = fs.readdirSync(DRIVERS)
  .filter((d) => d !== GENERIC && fs.statSync(path.join(DRIVERS, d)).isDirectory());

const models = {};
let deprecatedCount = 0;
const skipped = [];

for (const dir of dirs) {
  const composePath = path.join(DRIVERS, dir, 'driver.compose.json');
  const driverPath = path.join(DRIVERS, dir, 'driver.js');
  if (!fs.existsSync(composePath) || !fs.existsSync(driverPath)) { skipped.push(dir); continue; }

  const compose = JSON.parse(fs.readFileSync(composePath, 'utf8'));
  const js = fs.readFileSync(driverPath, 'utf8');
  const match = js.match(/hwType\s*===?\s*(\d+)/);
  if (!match) { skipped.push(dir); continue; }

  const hwType = Number(match[1]);
  if (models[hwType]) {
    console.warn(`hwType ${hwType} claimed by both ${models[hwType].driver} and ${dir}`);
    continue;
  }

  models[hwType] = {
    driver: dir,
    name: (compose.name && (compose.name.en || Object.values(compose.name)[0])) || dir,
    batteries: (compose.energy && compose.energy.batteries) || ['CR2450'],
  };

  if (compose.deprecated !== true) {
    // Insert the flag right after "name" so the manifests stay readable.
    const rebuilt = {};
    for (const [key, value] of Object.entries(compose)) {
      rebuilt[key] = value;
      if (key === 'name') rebuilt.deprecated = true;
    }
    if (!rebuilt.deprecated) rebuilt.deprecated = true;
    fs.writeFileSync(composePath, `${JSON.stringify(rebuilt, null, 2)}\n`);
    deprecatedCount++;
  }
}

const sorted = Object.keys(models).map(Number).sort((a, b) => a - b);

const lines = [
  "'use strict';",
  '',
  '/**',
  ' * hwType -> model metadata, generated by scripts/build-tag-models.js from the',
  ' * per-model drivers. Regenerate that script rather than editing this by hand.',
  ' *',
  ' * The AP already tells us the hwType of every tag, so this only supplies the',
  ' * things the AP does not: a human readable model name and the battery layout',
  ' * Homey wants for its energy screen.',
  ' */',
  '',
  'const TAG_MODELS = {',
];

for (const hw of sorted) {
  const m = models[hw];
  lines.push(`  ${hw}: { name: ${JSON.stringify(m.name)}, batteries: ${JSON.stringify(m.batteries)} },`
    + ` // 0x${hw.toString(16).padStart(2, '0').toUpperCase()} - legacy driver: ${m.driver}`);
}

lines.push('};');
lines.push('');
lines.push('/** Model name for a hwType, falling back to something readable. */');
lines.push('function modelName(hwType) {');
lines.push('  const model = TAG_MODELS[hwType];');
lines.push('  if (model) return model.name;');
lines.push('  return `Unknown model (hwType ${hwType})`;');
lines.push('}');
lines.push('');
lines.push('/** Battery layout for a hwType, for Device#setEnergy(). */');
lines.push('function batteries(hwType) {');
lines.push('  const model = TAG_MODELS[hwType];');
lines.push("  return (model && model.batteries) || ['CR2450'];");
lines.push('}');
lines.push('');
lines.push('module.exports = { TAG_MODELS, modelName, batteries };');
lines.push('');

fs.writeFileSync(OUT, lines.join('\n'));

console.log(`models written: ${sorted.length}`);
console.log(`drivers newly marked deprecated: ${deprecatedCount}`);
if (skipped.length) console.log(`skipped (no hwType filter): ${skipped.join(', ')}`);
console.log(`-> ${OUT}`);
